test_that('code lists preserve text and remain available offline', {
  cache <- withr::local_tempdir()
  source <- reference_source(system.file('examples', package = 'form.references'), cache)
  result <- get_code_lists(c('stations', 'observers', 'stations'), source)
  expect_identical(names(result$data), c('stations', 'observers'))
  expect_identical(result$data$stations$code, c('001', '002'))
  expect_identical(result$data$observers$code, c('ALICE', 'BOB'))
  expect_true(all(file.exists(result$paths)))
  expect_identical(get_code_lists(c('stations', 'observers'), source, offline = TRUE)$data, result$data)
  expect_error(get_code_lists('missing', source), 'absent from catalogue')
})

test_that('registry retrieval is separate and model-driven', {
  examples <- system.file('examples', package = 'form.references')
  cache <- withr::local_tempdir()
  registry <- reference_source(examples, cache, catalogue = 'registries')
  code_lists <- reference_source(examples, cache, catalogue = 'codelists')
  model <- form.model::load_form_model('survey', system.file('examples', package = 'form.model'))
  expect_identical(names(get_form_code_lists(model, code_lists)$data), c('observers', 'stations'))
  contacts <- get_form_registries(model, registry)
  expect_identical(names(contacts$data), 'contacts')
  expect_identical(contacts$data$contacts$email, c('alice@example.org', 'bob@example.org'))
  expect_identical(get_registries('contacts', registry, offline = TRUE)$data, contacts$data)
  expect_error(get_code_lists('contacts', registry), 'requires a codelists source')
  expect_error(get_registries('stations', code_lists), 'requires a registries source')
})

test_that('missing and corrupted cache entries are rejected offline', {
  source <- reference_source(system.file('examples', package = 'form.references'), withr::local_tempdir())
  expect_error(get_code_lists('stations', source, offline = TRUE), 'No cached catalogue')
  result <- get_code_lists('stations', source)
  writeLines('corrupted', result$paths[['stations']])
  expect_error(get_code_lists('stations', source, offline = TRUE), 'Verified cache unavailable')
  expect_identical(get_code_lists('stations', source)$data$stations$code, c('001', '002'))
})

test_that('checksum failures do not publish invalid downloaded files', {
  directory <- withr::local_tempdir()
  examples <- system.file('examples', package = 'form.references')
  file.copy(examples, directory, recursive = TRUE)
  copy <- file.path(directory, 'examples')
  writeLines('invalid data', file.path(copy, 'domain/survey/codelists/stations.csv'))
  source <- reference_source(copy, file.path(directory, 'cache'))
  expect_error(get_code_lists('stations', source), 'SHA-256 mismatch')
  expect_error(get_code_lists('stations', source, offline = TRUE), 'Verified cache unavailable')
})

test_that('source configuration rejects unsafe inputs and hides credentials', {
  cache <- withr::local_tempdir()
  expect_error(reference_source('https://name:secret@example.org/data', cache), 'without credentials')
  expect_error(reference_source('https://example.org/data?secret=x', cache), 'without credentials')
  expect_error(reference_source('https://example.org/', cache, timeout = 0), 'positive')
  expect_error(reference_source('https://example.org/', cache, max_connections = 1.5), 'whole number')
  source <- reference_source('https://example.org/', cache, headers = c(Authorization = 'secret-value'))
  expect_false(any(grepl('secret-value', capture.output(print(source)), fixed = TRUE)))
})

test_that('an invalid catalogue cannot replace the verified offline catalogue', {
  directory <- withr::local_tempdir()
  examples <- system.file('examples', package = 'form.references')
  file.copy(examples, directory, recursive = TRUE)
  copy <- file.path(directory, 'examples')
  source <- reference_source(copy, file.path(directory, 'cache'))
  before <- read_code_list_catalogue(source)
  catalogue_path <- file.path(copy, 'codelists.csv')
  catalogue <- utils::read.csv(catalogue_path, colClasses = 'character', fileEncoding = 'UTF-8-BOM')
  catalogue$csv_path[[1]] <- '../outside.csv'
  utils::write.csv(catalogue, catalogue_path, row.names = FALSE)
  metadata_path <- file.path(copy, 'codelists.yaml')
  metadata <- yaml::read_yaml(metadata_path)
  metadata$sha256 <- digest::digest(file = catalogue_path, algo = 'sha256')
  yaml::write_yaml(metadata, metadata_path)
  expect_error(read_code_list_catalogue(source), 'relative paths without traversal')
  expect_identical(read_code_list_catalogue(source, offline = TRUE), before)
})

test_that('YAML authentication uses environment secrets without printing them', {
  directory <- withr::local_tempdir()
  config <- file.path(directory, 'source.yaml')
  withr::local_envvar(c(FORM_TEST_PASSWORD = 'private-test-value'))
  writeLines(c('url: https://example.org/data/', paste0('cache: ', file.path(directory, 'cache')),
    'user: reader', 'password: !env FORM_TEST_PASSWORD'), config)
  source <- reference_source_from_yaml(config)
  expect_true(startsWith(source$headers[['Authorization']], 'Basic '))
  expect_false(any(grepl('private-test-value', capture.output(print(source)), fixed = TRUE)))
  writeLines(c('url: http://example.org/data/', paste0('cache: ', file.path(directory, 'cache')),
    'user: reader', 'password: !env FORM_TEST_PASSWORD'), config)
  expect_error(reference_source_from_yaml(config), 'requires an HTTPS')
})
